/* ============================================================
   layout.js — 装配布局表（装配态 = 一台立式中塔机箱）
   ============================================================

   为什么要有这一份：原来八个元件环成一圈飘在虚空里，看起来是八个
   互不相干的东西。现在它们按真实装机位置装进一只立式机箱 —— 开机时
   从打开的侧板外飞进来装好，点某个元件时它沿着抽出方向离开机箱并拆开。

   ── 世界约定（八个元件的 wrapper 都挂在这套坐标系下）──
     +Y = 上
     -Z = 机箱后部（I/O 挡板、PCIe 挡板、后部出风扇）
     +Z = 前部（进风口、前面板）
     +X = 打开的侧板那一侧 = 镜头看进去的方向 = 所有元件的抽出方向
     原点 = 机箱底板中心（Y = 0 就是地面）
   1 单位 ≈ 30 cm。机箱外部 0.80 × 1.70 × 1.72（case.js 按这个重建）。

   ── 这份数字是怎么来的 ──
   不是按毫米算的，是「看起来像一台真机 + 彼此不穿模」的结果：
   scale = 装配态想占的尺寸 / 模型自身的尺寸（每个元件的 modelBox 见注释）。
   机箱内腔是 X∈[-0.37,0.37]、Y∈[0.03,1.67]、Z∈[-0.83,0.83]，
   下面每一项的位置都保证落在内腔里（电源仓那一带 Y 最低、Z 最后）。

   改数字之前先量一遍：位置错了会穿模，scale 错了会顶出机箱。
   ============================================================ */

/* ── 装在主板上的元件共用的旋转 ──
   主板模型是「平铺」的：局部 X = 板长、Y = 朝上（元件面）、Z = 板宽。
   装进立式机箱后要把板立起来，所以映射为
     局部 +X → 世界 +Z（板长沿前后）
     局部 +Y → 世界 +X（元件面朝向打开的侧板 = 朝向镜头）
     局部 +Z → 世界 +Y（板宽沿上下）
   写成 three.js 默认的 XYZ 欧拉角就是 (-90°, 0, -90°)。 */
